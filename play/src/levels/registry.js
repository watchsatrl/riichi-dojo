/**
 * 思路卡。第 6 关把它交给玩家，对局里也随时能翻 —— 同一份 HTML，
 * 保证「学的时候看的」和「打的时候查的」不会漂移成两套说法。
 */
export function mindsetCardHTML() {
  return `<div class="mindset-card">
  <div class="mc-title">每一巡，问自己三个问题</div>
  <ol class="mc-list">
    ${MINDSET.perTurn.map((x) => `<li><b>${x.q}</b><span>${x.a}</span></li>`).join('')}
  </ol>
  <div class="mc-title">三个动作之前，各查一句</div>
  <table class="mc-table">
    <tbody>${MINDSET.before.map((x) =>
      `<tr><td class="mc-act">${x.act}</td><td><b>${x.q}</b><br><span>${x.why}</span></td></tr>`).join('')}
    </tbody>
  </table>
</div>`;
}

/**
 * 最小术语表。
 *
 * 这条是被读者骂出来的：第 2 关原本只写「先只看形状：4 个面子 + 1 个雀头就算」，
 * 然后直接让一个从没打过麻将的人判断牌型 —— 他不知道「面子」是什么。
 * 那不是「先动手撞墙」，是「先动手猜谜」。
 *
 * 修正后的原则：
 *   **先动手只在这个前提下成立 —— 玩家手里有足够的材料去推理。**
 *   需要新词汇或新概念的，必须先把最小够用的说明给出来，再让他动手。
 *
 * 判断标准很简单：**如果一个从没接触过的人看完这一屏，仍然只能靠猜，
 * 那就说明该讲的东西没讲。**
 */
export function terms(list) {
  return `<dl class="terms">${list
    .map(([t, d]) => `<dt>${t}</dt><dd>${d}</dd>`)
    .join('')}</dl>`;
}

/** 牌面图例：四类牌各给三张，够建立第一印象就行，不追求穷举 */
function tileLegend() {
  const row = (label, tiles, note) => `<div class="tl-row">
    <span class="tl-label">${label}</span>
    <span class="tl-tiles">${tiles.map((t) => tileSVG(t, { size: 'md' })).join('')}</span>
    <span class="tl-note">${note}</span>
  </div>`;
  return `<div class="tile-legend">
    ${row('萬子', [0, 1, 2], '写着汉字数字 · 一萬到九萬')}
    ${row('筒子', [9, 10, 11], '画着圆圈 · 一筒到九筒')}
    ${row('索子', [18, 19, 20], '画着竹节 · 一索到九索')}
    ${row('字牌', [27, 31, 33], '没有数字 · 東南西北 白發中')}
  </div>`;
}

